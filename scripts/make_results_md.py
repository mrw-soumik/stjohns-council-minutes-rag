"""Write eval/results/RESULTS.md from the JSON files in eval/results (no hand-typed numbers)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "eval" / "results"


def load(name: str) -> dict | None:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def table(runs: list[dict], latency: bool) -> list[str]:
    head = "| Configuration | hit@1 | hit@3 | hit@5 (95% CI) | recall@5 | MRR@10 |"
    sep = "|---|---|---|---|---|---|"
    if latency:
        head += " latency p50 / p95 (ms) |"
        sep += "---|"
    lines = [head, sep]
    for r in runs:
        m = r["metrics"]
        lo, hi = r["hit@5_ci95"]
        row = (
            f"| {r['config']['description']} | {m['hit@1']:.3f} | {m['hit@3']:.3f} | "
            f"**{m['hit@5']:.3f}** ({lo:.2f} to {hi:.2f}) | {m['recall@5']:.3f} | "
            f"{m['mrr@10']:.3f} |"
        )
        if latency:
            lat = r.get("latency_ms")
            row += f" {lat['p50']:.1f} / {lat['p95']:.1f} |" if lat else " n/a |"
        lines.append(row)
    return lines


def by_type(runs: list[dict]) -> list[str]:
    types = sorted({t for r in runs for t in r["by_type"]})
    lines = ["| Configuration | " + " | ".join(f"{t} (n)" for t in types) + " |"]
    lines.append("|---|" + "---|" * len(types))
    for r in runs:
        cells = []
        for t in types:
            v = r["by_type"].get(t)
            cells.append(f"{v['hit@5']:.2f} ({v['n']})" if v else "n/a")
        lines.append(f"| {r['config']['name']} | " + " | ".join(cells) + " |")
    return lines


def pa_tables(main_run: dict) -> list[str]:
    """PA-01 (wording subsets) and PA-02 (year, format) from per-question rows."""
    questions = {
        q["id"]: q
        for q in map(json.loads, (ROOT / "eval" / "questions.jsonl").read_text().splitlines())
        if q.get("answerable")
    }
    label = {"bm25": "Keyword only", "dense": "Semantic only", "hybrid": "Combined (hybrid)"}
    runs = {r["config"]["name"]: r for r in main_run["runs"] if r["config"]["name"] in label}

    def rate(rows: list[dict]) -> str:
        if not rows:
            return "n/a"
        hits = sum(r["hit@5"] for r in rows)
        return f"{hits / len(rows):.3f} ({int(hits)}/{len(rows)})"

    def subset(rows: list[dict], pred) -> list[dict]:
        return [r for r in rows if pred(questions[r["id"]])]

    out = [
        "## PA-01: hit@5 by wording",
        "",
        "Exact-term questions use the minutes' own words (names, addresses, numbers, titles); "
        "paraphrased questions avoid them on purpose.",
        "",
        "| Retrieval | All answerable | Exact-term | Paraphrased |",
        "|---|---|---|---|",
    ]
    for name, r in runs.items():
        rows = r["per_question"]
        out.append(
            f"| {label[name]} | {rate(rows)} | "
            f"{rate(subset(rows, lambda q: q['type'] != 'paraphrase'))} | "
            f"{rate(subset(rows, lambda q: q['type'] == 'paraphrase'))} |"
        )
    years = sorted({q["gold"][0]["meeting_date"][:4] for q in questions.values()})
    out += [
        "",
        "## PA-02: hit@5 by meeting year and source format",
        "",
        "Year of the (first) gold meeting. Every passage comes from the official HTML minutes; "
        "the PDF format is not applicable because the portal's PDF endpoint answers automated "
        "clients with a bot challenge, so no PDF-derived passages exist.",
        "",
        "| Retrieval | " + " | ".join(years) + " | HTML | PDF |",
        "|---|" + "---|" * (len(years) + 2),
    ]
    for name, r in runs.items():
        rows = r["per_question"]
        cells = [
            rate(subset(rows, lambda q, y=y: q["gold"][0]["meeting_date"].startswith(y)))
            for y in years
        ]
        out.append(f"| {label[name]} | " + " | ".join(cells) + f" | {rate(rows)} | n/a |")
    out.append("")
    return out


def main() -> None:
    out: list[str] = [
        "# Evaluation results",
        "",
        "Generated by `python scripts/make_results_md.py` from the JSON files in this folder.",
        "Every number below comes from a run recorded in those files. Commands to reproduce",
        "are in [`eval/README.md`](../README.md).",
        "",
    ]
    main_run = load("retrieval_main")
    if main_run:
        env = main_run["environment"]
        out += [
            "## Retrieval: main configurations",
            "",
            f"Run {env['run_at']} on {env['system']} {env['machine']}, Python {env['python']}. "
            f"{main_run['runs'][0]['n_answerable']} answerable questions, "
            f"{main_run['runs'][0]['n_chunks']:,} chunks. Latency is per query on CPU and "
            "includes embedding the query for dense and hybrid search.",
            "",
            *table(main_run["runs"], latency=True),
            "",
            "hit@5 by question type (hit rate, number of questions):",
            "",
            *by_type(main_run["runs"]),
            "",
        ]
        for r in main_run["runs"]:
            misses = ", ".join(r["misses_at_5"]) or "none"
            out.append(f"- `{r['config']['name']}` misses at 5: {misses}")
        out.append("")
        out += pa_tables(main_run)
    abl = load("retrieval_ablations")
    if abl:
        out += [
            "## Retrieval: ablations",
            "",
            "Each row changes one setting from the hybrid baseline (first row). These were "
            "measured on the same 65 questions used to develop the system, so small "
            "differences (one or two questions, about 0.015 to 0.03) are within noise.",
            "",
            *table(abl["runs"], latency=False),
            "",
        ]
        for r in abl["runs"]:
            if r.get("unreachable_gold"):
                out.append(
                    f"- `{r['config']['name']}`: gold evidence split across chunks for "
                    f"{', '.join(r['unreachable_gold'])} (cannot be retrieved as a whole)."
                )
        out.append("")
    for name, title in (
        ("demo_index_fp32_query", "Committed browser index (fp32 query model)"),
        ("demo_index_q8_query", "Committed browser index (q8 query model, as in the browser)"),
    ):
        run = load(name)
        if run:
            out += [
                f"## {title}",
                "",
                "Ranks with `docs/data` (int8 vectors, hashed BM25 terms) and the committed "
                "`eval/qrels.json`; this is what the CI gate runs. Latency is ranking only.",
                "",
                *table(run["runs"], latency=True),
                "",
            ]
    parity = load("embedding_parity")
    if parity:
        out += [
            "## Embedding parity (Python and transformers.js)",
            "",
            f"Model `{parity['model']}`; {parity['js_library']}; {parity['python']}; "
            f"{parity['n_texts']} sample texts.",
            "",
            "| Comparison | min cosine | mean cosine | max abs difference |",
            "|---|---|---|---|",
        ]
        for k, v in parity["comparisons"].items():
            out.append(
                f"| {k.replace('_', ' ')} | {v['cosine_min']:.6f} | {v['cosine_mean']:.6f} | "
                f"{v['max_abs_diff']:.6f} |"
            )
        out.append("")
    browser = ROOT / "docs" / "screenshots" / "browser-check.json"
    if browser.exists():
        b = json.loads(browser.read_text(encoding="utf-8"))["checks"]
        out += [
            "## Browser demo checks (headless Chrome)",
            "",
            f"- Search time after the model loads (embedding + ranking), five queries: "
            f"{', '.join(str(x) for x in b['search_ms'])} ms.",
            f"- Browser (WASM) versus Node query embeddings, q8 model: min cosine "
            f"{b['browser_vs_node_q8_cosine']['min']:.4f}.",
            f"- axe-core WCAG 2.1 A/AA violations: desktop light "
            f"{len(b['axe_desktop_light']['violations'])}, desktop dark "
            f"{len(b['axe_desktop_dark']['violations'])}, mobile "
            f"{len(b['axe_mobile_light']['violations'])}.",
            f"- Keyboard: first Tab reaches `{b['keyboard']['first_tab']}`; the skip link moves "
            f"focus to `#{b['keyboard']['after_skip_link']}`.",
            "- Horizontal scrolling at 390 px: "
            + ("yes." if b["mobile_horizontal_overflow"] else "no."),
            "",
        ]
    published = load("published_text")
    if published:
        rows = [
            (
                f"Excerpts (verbatim, decisions only, at most {published['excerpt_max_chars']} "
                "characters)",
                published["excerpts"],
            ),
            ('Recorded outcomes ("carried, 9 to 0")', published["outcomes"]),
            ("Item titles (shown with every result)", published["item_titles"]),
            ("Section headings (shown with every result)", published["section_headings"]),
        ]
        pa13 = published["pa13"]
        out += [
            "## Text published in the demo index (PA-13)",
            "",
            f"Measured against the parsed minutes ({published['parsed_minutes_chars']:,} "
            "characters) with `python scripts/published_text_share.py`.",
            "",
            "| Published | Count | Characters | Share of the minutes |",
            "|---|---|---|---|",
        ]
        out += [
            f"| {label} | {v['count']:,} | {v['chars']:,} | {v['share']:.1%} |" for label, v in rows
        ]
        out += [
            f"| Excerpts and outcomes together | | "
            f"{published['excerpts']['chars'] + published['outcomes']['chars']:,} | "
            f"{published['excerpts_and_outcomes_share']:.1%} |",
            "",
            f"PA-13: {pa13['checked']:,} excerpts checked against their source passages; longest "
            f"{pa13['longest']} characters; {len(pa13['violations'])} not verbatim or too long.",
            "",
        ]
    for summary_path in sorted(RESULTS.glob("answers_*/summary.json")):
        answers = json.loads(summary_path.read_text(encoding="utf-8"))
        out += answers.get("markdown", [])
        out += [f"Per-question rows: `{summary_path.parent.name}/results.jsonl`.", ""]
        if (summary_path.parent / "review.md").exists():
            out += [
                f"Read-through of these answers (errors the automatic grade misses): "
                f"`{summary_path.parent.name}/review.md`.",
                "",
            ]
    (RESULTS / "RESULTS.md").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
