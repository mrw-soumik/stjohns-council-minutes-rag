"""Write eval/results/RESULTS.md from the JSON files in eval/results (no hand-typed numbers)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "eval" / "results"


def load(name: str) -> dict | None:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def table(runs: list[dict], latency: bool) -> list[str]:
    head = "| Configuration | hit@1 | hit@3 | hit@5 (95% CI) | recall@5 | MRR@10 |"
    sep = "|---|---|---|---|---|---|"
    if latency:
        head += " latency p50 / p95 (ms) |"
        sep += "---|"
    lines = [head, sep]
    for r in runs:
        m = r["metrics"]
        lo, hi = r["hit@5_ci95"]
        row = (
            f"| {r['config']['description']} | {m['hit@1']:.3f} | {m['hit@3']:.3f} | "
            f"**{m['hit@5']:.3f}** ({lo:.2f} to {hi:.2f}) | {m['recall@5']:.3f} | "
            f"{m['mrr@10']:.3f} |"
        )
        if latency:
            lat = r.get("latency_ms")
            row += f" {lat['p50']:.1f} / {lat['p95']:.1f} |" if lat else " n/a |"
        lines.append(row)
    return lines


def by_type(runs: list[dict]) -> list[str]:
    types = sorted({t for r in runs for t in r["by_type"]})
    lines = ["| Configuration | " + " | ".join(f"{t} (n)" for t in types) + " |"]
    lines.append("|---|" + "---|" * len(types))
    for r in runs:
        cells = []
        for t in types:
            v = r["by_type"].get(t)
            cells.append(f"{v['hit@5']:.2f} ({v['n']})" if v else "n/a")
        lines.append(f"| {r['config']['name']} | " + " | ".join(cells) + " |")
    return lines


def main() -> None:
    out: list[str] = [
        "# Evaluation results",
        "",
        "Generated by `python scripts/make_results_md.py` from the JSON files in this folder.",
        "Every number below comes from a run recorded in those files. Commands to reproduce",
        "are in [`eval/README.md`](../README.md).",
        "",
    ]
    main_run = load("retrieval_main")
    if main_run:
        env = main_run["environment"]
        out += [
            "## Retrieval: main configurations",
            "",
            f"Run {env['run_at']} on {env['system']} {env['machine']}, Python {env['python']}. "
            f"{main_run['runs'][0]['n_answerable']} answerable questions, "
            f"{main_run['runs'][0]['n_chunks']:,} chunks. Latency is per query on CPU and "
            "includes embedding the query for dense and hybrid search.",
            "",
            *table(main_run["runs"], latency=True),
            "",
            "hit@5 by question type (hit rate, number of questions):",
            "",
            *by_type(main_run["runs"]),
            "",
        ]
        for r in main_run["runs"]:
            misses = ", ".join(r["misses_at_5"]) or "none"
            out.append(f"- `{r['config']['name']}` misses at 5: {misses}")
        out.append("")
    abl = load("retrieval_ablations")
    if abl:
        out += [
            "## Retrieval: ablations",
            "",
            "Each row changes one setting from the hybrid baseline (first row). These were "
            "measured on the same 65 questions used to develop the system, so small "
            "differences (one or two questions, about 0.015 to 0.03) are within noise.",
            "",
            *table(abl["runs"], latency=False),
            "",
        ]
        for r in abl["runs"]:
            if r.get("unreachable_gold"):
                out.append(
                    f"- `{r['config']['name']}`: gold evidence split across chunks for "
                    f"{', '.join(r['unreachable_gold'])} (cannot be retrieved as a whole)."
                )
        out.append("")
    for name, title in (
        ("demo_index_fp32_query", "Committed browser index (fp32 query model)"),
        ("demo_index_q8_query", "Committed browser index (q8 query model, as in the browser)"),
    ):
        run = load(name)
        if run:
            out += [
                f"## {title}",
                "",
                "Ranks with `docs/data` (int8 vectors, hashed BM25 terms) and the committed "
                "`eval/qrels.json`; this is what the CI gate runs. Latency is ranking only.",
                "",
                *table(run["runs"], latency=True),
                "",
            ]
    parity = load("embedding_parity")
    if parity:
        out += [
            "## Embedding parity (Python and transformers.js)",
            "",
            f"Model `{parity['model']}`; {parity['js_library']}; {parity['python']}; "
            f"{parity['n_texts']} sample texts.",
            "",
            "| Comparison | min cosine | mean cosine | max abs difference |",
            "|---|---|---|---|",
        ]
        for k, v in parity["comparisons"].items():
            out.append(
                f"| {k.replace('_', ' ')} | {v['cosine_min']:.6f} | {v['cosine_mean']:.6f} | "
                f"{v['max_abs_diff']:.6f} |"
            )
        out.append("")
    browser = ROOT / "docs" / "screenshots" / "browser-check.json"
    if browser.exists():
        b = json.loads(browser.read_text(encoding="utf-8"))["checks"]
        out += [
            "## Browser demo checks (headless Chrome)",
            "",
            f"- Search time after the model loads (embedding + ranking), five queries: "
            f"{', '.join(str(x) for x in b['search_ms'])} ms.",
            f"- Browser (WASM) versus Node query embeddings, q8 model: min cosine "
            f"{b['browser_vs_node_q8_cosine']['min']:.4f}.",
            f"- axe-core WCAG 2.1 A/AA violations: desktop light "
            f"{len(b['axe_desktop_light']['violations'])}, desktop dark "
            f"{len(b['axe_desktop_dark']['violations'])}, mobile "
            f"{len(b['axe_mobile_light']['violations'])}.",
            f"- Keyboard: first Tab reaches `{b['keyboard']['first_tab']}`; the skip link moves "
            f"focus to `#{b['keyboard']['after_skip_link']}`.",
            f"- Horizontal scrolling at 390 px: {'yes' if b['mobile_horizontal_overflow'] else 'no'}.",
            "",
        ]
    answers = load("answers_local")
    if answers:
        out += answers.get("markdown", [])
    (RESULTS / "RESULTS.md").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
